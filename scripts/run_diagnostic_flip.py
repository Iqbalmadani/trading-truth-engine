"""
TTE Diagnostic Mode — Signal Accuracy & Regime Boundary Validator

Runs the L1→L2→L3 pipeline WITHOUT Layer 4 execution.
Records EVERY signal (no OMS filtering) and measures:

1. DIRECTIONAL ACCURACY: Does the predicted direction match actual price movement?
   - Forward returns at 5, 10, 20, 50 candles after each signal
   - "Correct" = price moved in predicted direction by any amount

2. REGIME BOUNDARY RESPECT: Does price stay within CPD regime bounds?
   - After regime is identified, how many candles before price escapes?
   - Which direction does the escape happen?

3. SCORE-RETURN CORRELATION: Does higher score magnitude = bigger correct move?

This answers the fundamental question:
"Can TTE's engine predict direction at all, independent of SL/TP/sizing?"

--- FLIP MODE ---
This is a modified copy of run_diagnostic.py that adds a --flip flag.
It does NOT touch src/thresholds.py or src/executor.py — the production
code is untouched. Instead, it flips the recorded signal_type (LONG<->SHORT)
AFTER layer3() returns, purely for measurement purposes. This tests the
mean-reversion hypothesis: if score-high currently maps to LONG and that's
wrong, does mapping score-high to SHORT instead produce correct results?

Usage:
    python run_diagnostic_flip.py --exchange gateio --pair ETH_USDT --tf 1h --candles 800
    python run_diagnostic_flip.py --exchange gateio --pair ETH_USDT --tf 1h --candles 800 --flip

Run BOTH (with and without --flip) on the SAME data and compare the
"Primary metric (20-candle directional accuracy)" at the end of each report.
"""

