# Forward return horizons to measure (in candles)
HORIZONS = [5, 10, 20, 50]


def run_diagnostic(
    exchange: str,
    pair: str,
    timeframe: str,
    market_type: str,
    n_candles: int,
    min_warmup: int = 50,
    recal_interval: int = 100,
    flip: bool = False,
):
    """
    Run diagnostic mode: generate signals and measure forward returns
    without executing any trades.

    If flip=True, the recorded signal_type is inverted (LONG<->SHORT)
    AFTER layer3() decides it. This measures what accuracy WOULD have
    been if the mean-reversion hypothesis mapping were used, without
    touching any production threshold/executor logic.
    """
    print(f"\n{'='*70}")
    mode_label = "FLIP MODE (mean-reversion hypothesis)" if flip else "NORMAL MODE (current breakout mapping)"
    print(f"  TTE DIAGNOSTIC MODE — Signal Accuracy Validator — {mode_label}")
    print(f"  {exchange}/{pair}/{timeframe} | {n_candles} candles")
    print(f"{'='*70}\n")

    connector = get_connector(exchange)
    print("  Fetching candles...")
    candles = fetch_historical_ohlcv(connector, pair, timeframe, market_type, n_candles)

    if len(candles) < min_warmup + 10:
        print(f"  ERROR: Not enough candles ({len(candles)})")
        return

    print(f"  Fetched {len(candles)} candles")
    print("  Fetching scope data...")

    scope_histories = {}
    active_scopes = []
    for scope in ["ohlcv", "funding_rate", "volatility_compression"]:
        history = fetch_historical_scope(
            connector, pair, timeframe, market_type, scope, n_candles
        )
        if history and len(history) >= min_warmup:
            scope_histories[scope] = history
            active_scopes.append(scope)
            print(f"    {scope}: {len(history)} points")

    if not active_scopes:
        print("  ERROR: No active scopes")
        return

    close_prices = [c["close"] for c in candles]

    # Collectors
    all_signals = []       # Every signal generated by L3
    all_regimes = []       # Every regime detected by CPD
    score_history: List[float] = []
    penalty_score = 1.0
    penalty_price = 1.0
    model_score = "rbf"
    model_price = "rbf"

    signals_generated = 0
    neutral_count = 0

    print(f"\n  Walking forward from candle {min_warmup} to {len(candles)-1}...")
    print()

    for i in range(min_warmup, len(candles)):
        candle = candles[i]
        price_slice = close_prices[:i]

        if len(price_slice) < 3:
            continue

        # Recalibrate penalties periodically
        if i % recal_interval == 0 and len(score_history) >= 30:
            penalty_score, penalty_price, model_score, model_price = compute_bt_penalties(
                score_history, price_slice
            )

        # --- Run Layer 2 ---
        try:
            z_scores = {}
            scope_slice = {}
            for scope, history in scope_histories.items():
                slice_end = min(i, len(history))
                scope_slice[scope] = history[:slice_end]

            for scope in active_scopes:
                data = scope_slice.get(scope, [])
                if len(data) > 500:
                    data = data[-500:]
                if len(data) < 2:
                    z_scores[scope] = 0.0
                    continue
                pen = penalty_score if scope == "ohlcv" else penalty_price
                try:
                    window, _ = get_cpd_window(data, pen, model=model_score)
                    if len(window) < 2:
                        z_scores[scope] = 0.0
                    else:
                        z = zscore_in_window(window, data[-1])
                        z_scores[scope] = float(z) if not (np.isnan(z) or np.isinf(z)) else 0.0
                except Exception:
                    z_scores[scope] = 0.0

            current_score = sum(z_scores.values())
            if np.isnan(current_score) or np.isinf(current_score):
                current_score = 0.0

        except Exception as e:
            logger.warning(f"[{i}] L2 failed: {e}")
            continue

        score_history.append(current_score)

        if len(score_history) < 3:
            continue

        # --- Run Layer 3 ---
        try:
            layer3_output = layer3(
                current_score=current_score,
                score_history=score_history,
                current_price=candle["close"],
                price_history=price_slice,
                penalty_score=penalty_score,
                penalty_price=penalty_price,
                score_model=model_score,
                price_model=model_price,
            )
        except InsufficientScoreHistoryError:
            continue
        except Exception as e:
            continue

        entry = layer3_output.get("entry", "0")

        # --- FLIP MODE: invert direction for measurement only ---
        # This does NOT change how the real strategy would size, stop,
        # or target the trade (stop_loss/take_profit below are still
        # whatever layer3() computed for the ORIGINAL direction — that's
        # a separate, known-broken problem per Test 5). This flip ONLY
        # tests the directional accuracy hypothesis in isolation.
        if flip and entry in ("LONG", "SHORT"):
            entry = "SHORT" if entry == "LONG" else "LONG"

        if entry in ("LONG", "SHORT"):
            signals_generated += 1
            signal_record = {
                "candle_index": i,
                "entry_price": layer3_output["entry_price"],
                "signal_type": entry,
                "score": current_score,
                "stop_loss": layer3_output.get("stop_loss"),
                "take_profit": layer3_output.get("take_profit"),
                "rr": layer3_output.get("risk_reward_ratio", 0),
                "z_scores": dict(z_scores),
            }

            # Compute forward returns at each horizon
            forward_returns = {}
            for h in HORIZONS:
                future_idx = i + h
                if future_idx < len(candles):
                    future_close = candles[future_idx]["close"]
                    ret_pct = (future_close - candle["close"]) / candle["close"] * 100.0
                    forward_returns[h] = ret_pct

                    # Also track max favorable / max adverse excursion
                    # within the horizon
                    future_slice = candles[i+1:future_idx+1]
                    if future_slice:
                        highs = [c["high"] for c in future_slice]
                        lows = [c["low"] for c in future_slice]
                        max_up = (max(highs) - candle["close"]) / candle["close"] * 100.0
                        max_down = (min(lows) - candle["close"]) / candle["close"] * 100.0
                        forward_returns[f"{h}_mfe"] = max_up   # Max Favorable Excursion
                        forward_returns[f"{h}_mae"] = max_down  # Max Adverse Excursion
                else:
                    forward_returns[h] = None

            signal_record["forward_returns"] = forward_returns
            all_signals.append(signal_record)
        else:
            neutral_count += 1

        # --- Record regime boundary for CPD validation ---
        if i % 10 == 0:  # Sample every 10 candles for regime tracking
            try:
                cpd_window, _ = get_cpd_window(price_slice, penalty_price, model=model_price)
                if len(cpd_window) >= 2:
                    regime_high = max(cpd_window)
                    regime_low = min(cpd_window)
                    regime_range = regime_high - regime_low

                    # Check how long price stays within regime bounds
                    escape_candle = None
                    escape_dir = None
                    for j in range(i, min(i + 50, len(candles))):
                        if candles[j]["high"] > regime_high:
                            escape_candle = j - i
                            escape_dir = "UP"
                            break
                        elif candles[j]["low"] < regime_low:
                            escape_candle = j - i
                            escape_dir = "DOWN"
                            break

                    all_regimes.append({
                        "candle_index": i,
                        "regime_high": regime_high,
                        "regime_low": regime_low,
                        "regime_range_pct": (regime_range / candle["close"]) * 100,
                        "escape_candle": escape_candle,
                        "escape_dir": escape_dir,
                        "current_price": candle["close"],
                    })
            except Exception:
                pass

        # Progress
        if i % 100 == 0:
            print(
                f"  [{i:4d}/{len(candles)}] "
                f"score={current_score:+.3f} | "
                f"signal={entry:5s} | "
                f"total_signals={signals_generated}"
            )

    # =============================================
    # DIAGNOSTIC REPORT
    # =============================================
    print_diagnostic_report(all_signals, all_regimes, len(candles), min_warmup)


def print_diagnostic_report(
    signals: List[Dict],
    regimes: List[Dict],
    total_candles: int,
    warmup: int,
):
    """Print comprehensive diagnostic report."""
    sep = "=" * 70

    print(f"\n{sep}")
    print(f"  DIAGNOSTIC REPORT — TTE Signal Accuracy Analysis")
    print(f"{sep}")

    if not signals:
        print("  No signals generated — cannot analyze.")
        return

    longs = [s for s in signals if s["signal_type"] == "LONG"]
    shorts = [s for s in signals if s["signal_type"] == "SHORT"]

    print(f"\n  Total signals: {len(signals)} ({len(longs)} LONG, {len(shorts)} SHORT)")
    print(f"  Signal rate: {len(signals)}/{total_candles - warmup} = {len(signals)/(total_candles-warmup)*100:.1f}%")

    # ============================
    # TEST 1: DIRECTIONAL ACCURACY
    # ============================
    print(f"\n{sep}")
    print(f"  TEST 1: DIRECTIONAL ACCURACY")
    print(f"  'Did price move in the predicted direction?'")
    print(f"{sep}")

    for h in HORIZONS:
        correct = 0
        total = 0
        returns_correct = []
        returns_wrong = []

        for s in signals:
            fr = s["forward_returns"].get(h)
            if fr is None:
                continue
            total += 1
            if s["signal_type"] == "LONG" and fr > 0:
                correct += 1
                returns_correct.append(fr)
            elif s["signal_type"] == "SHORT" and fr < 0:
                correct += 1
                returns_correct.append(abs(fr))
            else:
                if s["signal_type"] == "LONG":
                    returns_wrong.append(abs(fr))
                else:
                    returns_wrong.append(abs(fr))

        if total > 0:
            acc = correct / total * 100
            avg_correct = np.mean(returns_correct) if returns_correct else 0
            avg_wrong = np.mean(returns_wrong) if returns_wrong else 0
            verdict = "[OK]" if acc > 55 else "[FAIL]" if acc < 45 else "[COIN FLIP]"
            print(
                f"\n  {h:2d}-candle horizon: "
                f"{correct}/{total} correct = {acc:.1f}% {verdict}"
            )
            print(f"     Avg correct move: {avg_correct:+.2f}%")
            print(f"     Avg wrong move:   {avg_wrong:+.2f}%")
        else:
            print(f"\n  {h:2d}-candle horizon: No data (signals too close to end)")

    # ============================
    # TEST 2: MFE/MAE ANALYSIS
    # ============================
    print(f"\n{sep}")
    print(f"  TEST 2: MAX FAVORABLE vs ADVERSE EXCURSION")
    print(f"  'Does price reach our side before hitting the wrong side?'")
    print(f"{sep}")

    for h in HORIZONS:
        favorable_wins = 0
        total_mfe_mae = 0

        for s in signals:
            mfe_key = f"{h}_mfe"
            mae_key = f"{h}_mae"
            mfe = s["forward_returns"].get(mfe_key)
            mae = s["forward_returns"].get(mae_key)
            if mfe is None or mae is None:
                continue

            total_mfe_mae += 1
            if s["signal_type"] == "LONG":
                # For LONG, favorable = up, adverse = down
                if mfe > abs(mae):
                    favorable_wins += 1
            else:
                # For SHORT, favorable = down, adverse = up
                if abs(mae) > mfe:
                    favorable_wins += 1

        if total_mfe_mae > 0:
            fav_pct = favorable_wins / total_mfe_mae * 100
            verdict = "[OK]" if fav_pct > 55 else "[FAIL]" if fav_pct < 45 else "[COIN FLIP]"
            print(f"\n  {h:2d}-candle: MFE > MAE in {favorable_wins}/{total_mfe_mae} = {fav_pct:.1f}% {verdict}")

    # ============================
    # TEST 3: SCORE MAGNITUDE CORRELATION
    # ============================
    print(f"\n{sep}")
    print(f"  TEST 3: SCORE MAGNITUDE vs FORWARD RETURN CORRELATION")
    print(f"  'Does a bigger score mean a bigger correct move?'")
    print(f"{sep}")

    for h in HORIZONS:
        scores = []
        returns = []
        for s in signals:
            fr = s["forward_returns"].get(h)
            if fr is None:
                continue
            # Directional return: positive = correct direction
            if s["signal_type"] == "LONG":
                dir_return = fr
            else:
                dir_return = -fr
            scores.append(abs(s["score"]))
            returns.append(dir_return)

        if len(scores) >= 5:
            corr = float(np.corrcoef(scores, returns)[0, 1])
            verdict = "[OK]" if corr > 0.2 else "[WEAK]" if corr > 0 else "[INVERSE!]"
            print(f"\n  {h:2d}-candle: Correlation = {corr:+.3f} {verdict}")
        else:
            print(f"\n  {h:2d}-candle: Not enough data")

    # ============================
    # TEST 4: LONG vs SHORT BIAS
    # ============================
    print(f"\n{sep}")
    print(f"  TEST 4: DIRECTIONAL BIAS")
    print(f"  'Is the engine biased toward LONG or SHORT?'")
    print(f"{sep}")

    h_test = 20
    long_correct = 0
    long_total = 0
    short_correct = 0
    short_total = 0

    for s in signals:
        fr = s["forward_returns"].get(h_test)
        if fr is None:
            continue
        if s["signal_type"] == "LONG":
            long_total += 1
            if fr > 0:
                long_correct += 1
        else:
            short_total += 1
            if fr < 0:
                short_correct += 1

    if long_total > 0:
        print(f"\n  LONG accuracy  ({h_test}c): {long_correct}/{long_total} = {long_correct/long_total*100:.1f}%")
    if short_total > 0:
        print(f"  SHORT accuracy ({h_test}c): {short_correct}/{short_total} = {short_correct/short_total*100:.1f}%")

    long_pct = len(longs) / len(signals) * 100
    print(f"\n  Signal distribution: {long_pct:.0f}% LONG / {100-long_pct:.0f}% SHORT")

    # ============================
    # TEST 5: REGIME BOUNDARY RESPECT
    # ============================
    print(f"\n{sep}")
    print(f"  TEST 5: REGIME BOUNDARY RESPECT RATE")
    print(f"  'Does price stay within CPD regime bounds?'")
    print(f"{sep}")

    if regimes:
        escaped = [r for r in regimes if r["escape_candle"] is not None]
        held = [r for r in regimes if r["escape_candle"] is None]

        print(f"\n  Regimes sampled: {len(regimes)}")
        print(f"  Escaped within 50 candles: {len(escaped)} ({len(escaped)/len(regimes)*100:.0f}%)")
        print(f"  Held boundary (50c): {len(held)} ({len(held)/len(regimes)*100:.0f}%)")

        if escaped:
            escape_times = [r["escape_candle"] for r in escaped]
            print(f"\n  Avg escape time: {np.mean(escape_times):.1f} candles")
            print(f"  Median escape time: {np.median(escape_times):.1f} candles")
            print(f"  Min: {min(escape_times)}c, Max: {max(escape_times)}c")

            up_escapes = sum(1 for r in escaped if r["escape_dir"] == "UP")
            down_escapes = sum(1 for r in escaped if r["escape_dir"] == "DOWN")
            print(f"\n  Escape direction: {up_escapes} UP / {down_escapes} DOWN")

        regime_ranges = [r["regime_range_pct"] for r in regimes]
        print(f"\n  Regime range: min={min(regime_ranges):.2f}%, median={np.median(regime_ranges):.2f}%, max={max(regime_ranges):.2f}%")
    else:
        print("  No regime data collected.")

    # ============================
    # TEST 6: SIGNAL-BY-SIGNAL DETAIL
    # ============================
    print(f"\n{sep}")
    print(f"  SIGNAL-BY-SIGNAL DETAIL")
    print(f"{sep}")

    for s in signals:
        fr5 = s["forward_returns"].get(5)
        fr10 = s["forward_returns"].get(10)
        fr20 = s["forward_returns"].get(20)
        fr50 = s["forward_returns"].get(50)

        def fmt_ret(r, direction):
            if r is None:
                return "  N/A "
            correct = (direction == "LONG" and r > 0) or (direction == "SHORT" and r < 0)
            mark = "+" if correct else "X"
            return f"{r:+5.2f}%{mark}"

        print(
            f"  [{s['candle_index']:4d}] {s['signal_type']:5s} "
            f"score={s['score']:+6.2f} "
            f"entry={s['entry_price']:.2f} "
            f"RR={s.get('rr', 0):.2f} | "
            f"5c={fmt_ret(fr5, s['signal_type'])} "
            f"10c={fmt_ret(fr10, s['signal_type'])} "
            f"20c={fmt_ret(fr20, s['signal_type'])} "
            f"50c={fmt_ret(fr50, s['signal_type'])}"
        )

    # ============================
    # VERDICT
    # ============================
    print(f"\n{sep}")
    print(f"  FINAL VERDICT")
    print(f"{sep}")

    # Calculate 20-candle accuracy as main metric
    correct_20 = 0
    total_20 = 0
    for s in signals:
        fr = s["forward_returns"].get(20)
        if fr is None:
            continue
        total_20 += 1
        if (s["signal_type"] == "LONG" and fr > 0) or (s["signal_type"] == "SHORT" and fr < 0):
            correct_20 += 1

    if total_20 > 0:
        acc_20 = correct_20 / total_20 * 100
        print(f"\n  Primary metric (20-candle directional accuracy): {acc_20:.1f}%")
        print()

        if acc_20 > 60:
            print("  [STRONG] Engine CAN predict direction.")
            print("  --> Problem is in SL/TP and execution, not in scoring.")
            print("  --> Focus: redesign exit strategy (trailing, dynamic SL/TP)")
        elif acc_20 > 55:
            print("  [MARGINAL] Engine has slight edge.")
            print("  --> Edge exists but may not survive friction.")
            print("  --> Focus: reduce friction impact + improve RR asymmetry")
        elif acc_20 > 45:
            print("  [COIN FLIP] Engine cannot predict direction.")
            print("  --> Scoring system needs fundamental rework.")
            print("  --> Focus: rethink what z-score sum actually measures")
        else:
            print("  [INVERSE] Engine predicts the WRONG direction!")
            print("  --> Contrarian strategy may work (flip signals)")
            print("  --> Or: fundamental misunderstanding of what score means")

    print(f"\n{sep}\n")


def setup_logging():
    log_dir = Path(__file__).parent.parent / "logs"
    log_dir.mkdir(parents=True, exist_ok=True)
    log_file = log_dir / "diagnostic.log"

    root = logging.getLogger()
    root.handlers = []
    root.setLevel(logging.INFO)

    fh = logging.FileHandler(log_file, mode="w", encoding="utf-8")
    fh.setLevel(logging.DEBUG)
    fh.setFormatter(logging.Formatter(
        "%(asctime)s - %(name)s - %(levelname)s - %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S"
    ))
    root.addHandler(fh)

    ch = logging.StreamHandler()
    ch.setLevel(logging.WARNING)
    ch.setFormatter(logging.Formatter("%(levelname)s: %(message)s"))
    root.addHandler(ch)

    return log_file


